3️⃣ Am / Is / Are-এর Rule
এটা খুব ভালোভাবে মুখস্থ করো।
Shortcut:
I → am
He/She/It → is
You/We/They → are
4️⃣ Positive Sentence
I → am
I am learning English.
I am reading a book.
I am watching TV.
He/She/It → is
He is playing football.
She is cooking dinner.
It is raining.
You/We/They → are
You are learning English.
We are studying.
They are playing football.
5️⃣ Negative Sentence
Formula:
Subject + am/is/are + not + V-ing + Object
I:       I am not studying now.
He:    He is not playing football.
She:  She is not cooking.
They: They are not watching TV.
