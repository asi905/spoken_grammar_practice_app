📘 DAY 9 — PRESENT PERFECT CONTINUOUS TENSE
have/has + been + V-ing
আজ আমরা Present Tense-এর ৪র্থ এবং শেষ form — Present Perfect Continuous শিখব।
এটি বিশেষভাবে ব্যবহার হয় যখন কোনো কাজ অতীতে শুরু হয়ে এখনও চলছে, অথবা কতক্ষণ ধরে কাজটি চলছে—এটা বোঝাতে।
1️⃣ Present Perfect Continuous কী?
যে কাজ অতীতে শুরু হয়েছে এবং এখনও চলছে, অথবা কাজটি কিছু সময় ধরে চলেছে—তা বোঝাতে Present Perfect Continuous ব্যবহার করা হয়।
Example:
I have been studying English for two hours.
আমি দুই ঘণ্টা ধরে English পড়ছি।
কাজটি:
অতীতে শুরু হয়েছে
দুই ঘণ্টা ধরে চলছে
এখনও চলছে
2️⃣ Basic Formula ⭐⭐⭐
Positive:
Subject + have/has + been + V-ing + Object
Examples:
I have been studying English.
She has been working here.
They have been playing football.
3️⃣ Have / Has-এর Rule
Shortcut:
I/You/We/They → have been
He/She/It → has been
4️⃣ Positive Sentence
I / You / We / They
I have been learning English.
You have been working hard.
We have been studying for two hours.
They have been playing football.
He / She / It
He has been studying English.
She has been cooking for an hour.
It has been raining since morning.
5️⃣ Since এবং For ⭐⭐⭐
Present Perfect Continuous-এ since এবং for খুব গুরুত্বপূর্ণ।
Since = কখন থেকে
Since + starting point
Examples:
since morning
since Monday
since 2020
since January
since 5 PM
since childhood
Example:
I have been studying since morning.
আমি সকাল থেকে পড়ছি।
She has been working here since 2020.
6️⃣ For = কত সময় ধরে
For + duration
Examples:
for two hours
for five days
for three years
for ten minutes
for a long time
Example:
I have been studying for two hours.
আমি দুই ঘণ্টা ধরে পড়ছি।
He has been working here for five years.
⭐ Since vs For
সহজভাবে:
Since → Starting point
since 2020
কখন থেকে?
For → Duration
for six years
কত বছর ধরে?
