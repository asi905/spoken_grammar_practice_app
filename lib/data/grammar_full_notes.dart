📘 DAY 5 — VERB
English Grammar Course | Basic → Spoken English
আজকের topic খুবই গুরুত্বপূর্ণ। কারণ English sentence-এর মূল চালিকাশক্তি হলো Verb। Tense, Voice, Question, Negative Sentence—প্রায় সব জায়গাতেই Verb-এর সঠিক ব্যবহার দরকার।
আজ আমরা শিখব:
Verb কী?
Main Verb
Helping/Auxiliary Verb
Be / Do / Have
