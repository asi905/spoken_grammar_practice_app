এখানে consonant double হবে না।
1️⃣1️⃣ Present Simple vs Present Continuous ⭐⭐⭐
এই পার্থক্যটি খুব গুরুত্বপূর্ণ।
Present Simple = অভ্যাস/নিয়মিত কাজ
I play football every day.
আমি প্রতিদিন football খেলি।
Present Continuous = এখন চলছে
I am playing football now.
আমি এখন football খেলছি।
আরেকটি Example:
She reads books every night.
সে প্রতি রাতে বই পড়ে।
→ Habit → Present Simple
কিন্তু:
She is reading a book now.
সে এখন একটি বই পড়ছে।
→ এখন চলছে → Present Continuous
1️⃣2️⃣ Signal Words
Present Continuous-এর সঙ্গে প্রায়ই দেখা যায়:
now
right now
at the moment
currently
at present
today
these days
Examples:
I am studying now.
She is working at the moment.
They are currently living in Dhaka.
⚠️ একটি গুরুত্বপূর্ণ বিষয়
Today/these days থাকলেই সবসময় Present Continuous হবে—এমন নয়।
Context দেখতে হবে।
I am working from home today.
আজ সাময়িকভাবে করছি → Continuous।
কিন্তু:
I work from home.
সাধারণ নিয়ম/অভ্যাস → Simple।
1️⃣3️⃣ কিছু Verb সাধারণত Continuous-এ ব্যবহার করা হয় না
এগুলোকে সাধারণভাবে Stative Verbs বলা হয়।
যেমন:
