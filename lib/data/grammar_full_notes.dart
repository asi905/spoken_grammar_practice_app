আজ আমরা Pronoun খুব ভালোভাবে শিখব। Pronoun-এর সবচেয়ে গুরুত্বপূর্ণ বিষয় হলো—কোথায় I, me, my, mine, myself; কোথায় he, him, his; কোথায় they, them, their, theirs ব্যবহার করতে হবে।
1️⃣ Pronoun কী?
Noun-এর পরিবর্তে যে word ব্যবহার করা হয়, তাকে Pronoun বলে।
Example:
Rahim is a student. Rahim reads books. Rahim plays football.
এখানে Rahim বারবার ব্যবহার করলে sentence awkward হয়।
তাই:
Rahim is a student. He reads books. He plays football.
এখানে He = Pronoun।
2️⃣ Personal Pronoun
সবচেয়ে গুরুত্বপূর্ণ Pronoun হলো Personal Pronoun।
এগুলো দুইভাবে বুঝবে:
Subject Form
যে কাজ করে।
Object Form
যার ওপর কাজ হয়।
3️⃣ I vs Me ⭐
এটা খুব গুরুত্বপূর্ণ।
I = Subject
যখন আমি কাজটি করছি, তখন I।
I eat rice.
I study English.
I play football.
Me = Object
যখন কাজটি আমার ওপর হচ্ছে, তখন me।
He called me.
She helped me.
They invited me.
❌ Me study English.
✅ I study English.
❌ He helped I.
✅ He helped me.
4️⃣ He vs Him
He = Subject
He plays football.
He is my friend.
Him = Object
I called him.
She helped him.
I know him.
Shortcut:
He → কাজ করে
Him → কাজ তার ওপর হয়
5️⃣ She vs Her
She = Subject
She is beautiful.
She studies English.
Her = Object / Possessive
I called her.
I helped her.
This is her book.
এখানে her-এর ব্যবহার দুই ধরনের:
I saw her. → Object
Her book is new. → Possessive
6️⃣ We vs Us
We = Subject
We are students.
We play cricket.
Us = Object
The teacher helped us.
He called us.
She invited us.
7️⃣ They vs Them
They = Subject
They are my friends.
They play football.
Them = Object
I know them.
I called them.
She helped them.
8️⃣ Possessive Pronoun
এখন আসি my, your, his, her, our, their-এ।
এগুলো ownership/সম্পর্ক বোঝায়।
Example:
This is my book.
That is your phone.
This is his car.
This is her bag.
That is our university.
This is their house.
9️⃣ My vs Mine ⭐
এখানে অনেকেই ভুল করে।
My + Noun
This is my book.
This is my phone.
my-এর পরে Noun থাকে।
Mine = একাই বসতে পারে
This book is mine.
This phone is mine.
❌ This is mine book.
✅ This is my book.
❌ This book is my.
✅ This book is mine.
সহজ Rule:
my + noun
mine → noun ছাড়া
🔟 Your vs Yours
Your + Noun
Is this your phone?
Yours
Is this phone yours?
1️⃣1️⃣ His
His দু'ভাবেই ব্যবহার করা যায়।
His + Noun:
This is his car.
His একা:
This car is his.
1️⃣2️⃣ Her vs Hers
Her + Noun:
This is her bag.
Hers:
This bag is hers.
1️⃣3️⃣ Our vs Ours
This is our house.
This house is ours.
1️⃣4️⃣ Their vs Theirs
This is their car.
This car is theirs.
⭐ Complete Possessive Table
এটা ভালোভাবে মুখস্থ করো।
1️⃣5️⃣ Reflexive Pronoun
যখন Subject নিজেই নিজের ওপর কাজ করে, তখন Reflexive Pronoun ব্যবহার হয়।
Examples:
I hurt myself.
আমি নিজেকে আঘাত করেছি।
He introduced himself.
সে নিজেকে পরিচয় করিয়ে দিল।
She taught herself English.
সে নিজে নিজে English শিখেছে।
We enjoyed ourselves.
আমরা নিজেরা আনন্দ করেছি।
They prepared themselves.
তারা নিজেদের প্রস্তুত করেছে।
1️⃣6️⃣ Myself-এর Common Mistake ⭐
অনেকে মনে করে:
❌ Myself Atik.
এটা standard English introduction হিসেবে ঠিক নয়।
সঠিক:
I am Atikur.
অথবা:
My name is Asif.
তবে:
I introduced myself.
এখানে myself সঠিক।
1️⃣7️⃣ Demonstrative Pronoun
কাছের/দূরের জিনিস দেখাতে:
This = এটি/এটা
একটি, কাছে
This is my phone.
That = ওটি/ওটা
একটি, দূরে
That is my car.
These = এগুলো
একাধিক, কাছে
These are my books.
Those = ওগুলো
একাধিক, দূরে
Those are my shoes.
Golden Rule ⭐
This → singular
That → singular
These → plural
Those → plural
1️⃣8️⃣ Who / Whom / Whose
Who = কে
Who are you?
Who called me?
Whom = কাকে
Formal English-এ object হিসেবে:
Whom did you call?
Spoken English-এ অনেক সময়:
Who did you call?
দুটোই context অনুযায়ী দেখা যায়, তবে formal grammar-এ whom = object।
Whose = কার
Whose book is this?
Whose phone is that?
