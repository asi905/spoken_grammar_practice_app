understand
believe
like
love
want
need
remember
belong
সাধারণভাবে:
❌ I am knowing him.
✅ I know him.
❌ I am understanding.
✅ I understand.
❌ I am wanting some water.
✅ I want some water.
তবে কিছু verb-এর ক্ষেত্রে context অনুযায়ী continuous ব্যবহার সম্ভব—তাই এটাকে absolute rule হিসেবে ধরবে না।
