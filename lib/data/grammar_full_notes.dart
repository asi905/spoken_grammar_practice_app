1️⃣ Verb কী?
যে word দ্বারা কোনো কাজ (action), অবস্থা (state), বা ঘটনা বোঝায়, তাকে Verb বলে।
Action:
eat = খাওয়া
go = যাওয়া
come = আসা
play = খেলা
read = পড়া
write = লেখা
speak = বলা
work = কাজ করা
State:
be = হওয়া/থাকা
know = জানা
like = পছন্দ করা
love = ভালোবাসা
understand = বোঝা
believe = বিশ্বাস করা
Example:
I eat rice.
She reads books.
He is happy.
এখানে eat, reads, is—সবগুলোই Verb।
2️⃣ Main Verb কী?
যে Verb sentence-এর মূল কাজ বা action/state প্রকাশ করে, তাকে Main Verb বলে।
Example:
I play football.
play = Main Verb
She reads books.
reads = Main Verb
They work hard.
work = Main Verb
3️⃣ Helping Verb / Auxiliary Verb
যে Verb Main Verb-কে সাহায্য করে, তাকে Helping Verb বা Auxiliary Verb বলে।
প্রধান Auxiliary Verb:
Be
am, is, are, was, were, be, been, being
Have
have, has, had
Do
do, does, did
এগুলো Tense, Question, Negative, Passive ইত্যাদিতে খুব গুরুত্বপূর্ণ।
4️⃣ Be Verb
Be-এর বিভিন্ন form:
Present:
I am happy.
He is happy.
They are happy.
Past:
I was tired.
He was sick.
They were busy.
5️⃣ Be কখন Main Verb?
Be সবসময় Helping Verb নয়।
Example:
He is a doctor.
এখানে is-এর পরে কোনো main verb নেই।
তাই is = Main Verb / Linking Verb হিসেবে কাজ করছে।
কিন্তু:
He is reading a book.
এখানে:
is = Helping Verb
reading = Main Verb
6️⃣ Do Verb
Do-এর forms:
do → does → did
এগুলো দুইভাবে ব্যবহার হয়।
Main Verb হিসেবে:
I do my homework.
এখানে do = Main Verb.
Helping Verb হিসেবে:
Do you like coffee?
এখানে do = Helping Verb.
I do not like coffee.
এখানে do = Helping Verb.
Does he play football?
He does not play football.
7️⃣ Have Verb
Have-এর forms:
have → has → had
Main Verb:
I have a car.
এখানে have = Main Verb।
Helping Verb:
I have finished my work.
এখানে:
have = Helping Verb
finished = Main Verb
আর:
She has eaten lunch.
has = Helping Verb
eaten = Main Verb
8️⃣ Verb-এর 5 Forms ⭐⭐⭐
এটি আজকের সবচেয়ে গুরুত্বপূর্ণ অংশ।
একটি Verb-এর সাধারণত 5টি form শেখানো হয়:
অর্থাৎ:
Go – Went – Gone – Going – Goes
9️⃣ আরেকটি Example — Eat
Sentence:
V1:  I eat rice.
V2: I ate rice.
V3: I have eaten rice.
V4: I am eating rice.
V5: He eats rice.
🔟 V1 কখন ব্যবহার হয়?
V1 মূলত:
Simple Present-এ
I play football.
They go to school.
কিন্তু He/She/It হলে V5:
He plays football.
She goes to school.
Modal-এর পরে:
I can go.
He should study.
You must work.
⚠️ এখানে can goes হবে না।
❌ He can goes.
✅ He can go.
1️⃣1️⃣ V2 — Past Simple
Past Simple-এ সাধারণত V2 ব্যবহার হয়।
I went to Dhaka.
She ate rice.
He played football.
They watched a movie.
1️⃣2️⃣ V3 — Past Participle
V3 সবচেয়ে বেশি ব্যবহৃত হয়:
Perfect Tense
I have eaten.
She has gone.
They had finished the work.
Passive Voice
The work was done.
The book was written by him.
তাই V3 খুব গুরুত্বপূর্ণ।
1️⃣3️⃣ V4 — Ing Form
V4 হলো:
Verb + ing
Examples:
go → going
eat → eating
read → reading
play → playing
write → writing
Continuous Tense-এ ব্যবহার হয়:
I am reading.
She is writing.
They are playing.
1️⃣4️⃣ V5 — s/es Form
Present Simple-এ He/She/It বা singular third person-এর সাথে সাধারণত V5 হয়।
Example:
I play.
He plays.
They work.
She works.
We go.
He goes.
⭐ গুরুত্বপূর্ণ Rule
I / You / We / They → V1
I play.
You play.
We play.
They play.
He / She / It → V5
He plays.
She plays.
It works.
1️⃣5️⃣ Transitive Verb
যে Verb-এর পরে সাধারণত Object প্রয়োজন হয়, তাকে Transitive Verb বলে।
Example:
I eat rice.
eat → Verb
rice → Object
She reads a book.
reads → Verb
a book → Object
আরও:
He bought a phone.
I opened the door.
1️⃣6️⃣ Intransitive Verb
যে Verb-এর পরে Object প্রয়োজন হয় না, তাকে Intransitive Verb বলে।
Examples:
Birds fly.
He slept.
The baby cried.
They arrived.
এখানে Verb-এর পরে কোনো direct object নেই।
মনে রাখো:
Transitive → Object আছে
Intransitive → Direct Object নেই
