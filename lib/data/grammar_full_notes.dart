📘 DAY 8 — PRESENT PERFECT TENSE
have / has + V3
আজ আমরা Present Perfect Tense শিখব। এটি Spoken English-এ খুবই গুরুত্বপূর্ণ, বিশেষ করে কাজ শেষ হয়েছে, অভিজ্ঞতা হয়েছে, সদ্য ঘটেছে, অথবা অতীতে শুরু হয়ে এখনো সম্পর্ক আছে—এসব বোঝাতে।
1️⃣ Present Perfect Tense কী?
যে কাজ অতীতে কোনো এক সময়ে ঘটেছে কিন্তু তার ফলাফল/সম্পর্ক বর্তমানের সঙ্গে আছে, অথবা কাজটি সম্পন্ন হয়েছে—তা বোঝাতে Present Perfect ব্যবহার করা হয়।
Basic Formula:
Subject + have/has + V3 + Object
Examples:
I have eaten rice.
She has finished her work.
They have gone home.
2️⃣ Have / Has-এর Rule ⭐⭐⭐
Shortcut:
I/You/We/They → have
He/She/It → has
3️⃣ V3 কেন লাগে?
Present Perfect-এর মূল structure:
have/has + V3
Example:
eat → ate → eaten
I have eaten.
❌ I have ate.
✅ I have eaten.
go → went → gone
She has gone home.
❌ She has went home.
write → wrote → written
He has written a letter.
4️⃣ Positive Sentence
I / You / We / They → have + V3
I have finished my work.
You have done well.
We have completed the project.
They have gone home.
He / She / It → has + V3
He has finished his work.
She has eaten lunch.
It has stopped raining.
5️⃣ Negative Sentence
Formula:
Subject + have/has + not + V3
I/You/We/They:
I have not finished my work.
Short:
I haven't finished my work.
He/She/It:
She has not finished her work.
Short:
She hasn't finished her work.
Examples:
I haven't seen him.
We haven't finished yet.
They haven't arrived.
He hasn't called me.
She hasn't eaten yet.
6️⃣ Question Formation
Formula:
Have/Has + Subject + V3 + ...?
Have:
Have you eaten?
Have they arrived?
Have you finished your work?
Has:
Has he eaten?
Has she finished her work?
Has Rahim gone home?
7️⃣ Short Answer
