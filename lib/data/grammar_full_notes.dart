🔟 V-ing বানানোর Rules ⭐⭐⭐
Present Continuous-এ Main Verb-এর সাথে -ing যোগ করতে হয়।
কিন্তু সবসময় শুধু + ing করলেই হয় না।
Rule 1 — সাধারণভাবে + ing
play → playing
read → reading
eat → eating
work → working
speak → speaking
Rule 2 — শেষে e থাকলে e বাদ দিয়ে + ing
make → making
write → writing
take → taking
come → coming
dance → dancing
❌ makeing
✅ making
❌ writeing
✅ writing
Rule 3 — ie → y + ing
lie → lying
die → dying
tie → tying
Rule 4 — Short vowel + consonant হলে consonant double হতে পারে
run → running
sit → sitting
get → getting
swim → swimming
stop → stopping
কিন্তু:
play → playing
