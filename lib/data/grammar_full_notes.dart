1️⃣1️⃣ “How long” + Since/For
এই pattern-টি খুব ভালোভাবে শিখবে:
Question:
How long have/has + Subject + been + V-ing?
Answer:
Subject + have/has + been + V-ing + since/for...
Example:
How long have you been learning English?
I have been learning English for two years.
1️⃣2️⃣ Present Perfect vs Present Perfect Continuous ⭐⭐⭐
দুটো দেখতে কাছাকাছি, কিন্তু focus আলাদা।
Present Perfect
I have read three books.
এখানে গুরুত্ব:
কাজ কতটা সম্পন্ন হয়েছে / result
তিনটি বই পড়া শেষ হয়েছে।
Present Perfect Continuous
I have been reading for three hours.
এখানে গুরুত্ব:
কতক্ষণ ধরে কাজটি চলছে
তিন ঘণ্টা ধরে পড়ছি।
1️⃣3️⃣ আরও একটি Example
Present Perfect:
She has written five pages.
Focus = পাঁচ পৃষ্ঠা লেখা হয়েছে।
Present Perfect Continuous:
She has been writing for three hours.
Focus = তিন ঘণ্টা ধরে লিখছে।
1️⃣4️⃣ আরেকটি গুরুত্বপূর্ণ পার্থক্য
I have worked here for five years.
এটি Present Perfect।
I have been working here for five years.
এটি Present Perfect Continuous।
দুটিই grammatical এবং অনেক context-এ কাছাকাছি অর্থ দিতে পারে।
তবে Continuous version-এ কাজের ongoing duration/activity-এর ওপর বেশি emphasis থাকে।
1️⃣5️⃣ কখন Present Perfect Continuous ব্যবহার করবে?
① Past থেকে এখন পর্যন্ত চলমান কাজ
I have been learning English for two years.
② কতক্ষণ ধরে কাজ চলছে
She has been studying for three hours.
③ কাজের recent activity-এর evidence আছে
You are tired because you have been working all day.
তুমি ক্লান্ত কারণ তুমি সারাদিন কাজ করে আসছ।
④ Recently চলা কাজ
It has been raining since morning.
সকাল থেকে বৃষ্টি হচ্ছে।
1️⃣6️⃣ Present Perfect Continuous সবসময় কি এখনো চলছে?
না।
কখনও কাজটি সদ্য শেষও হতে পারে, কিন্তু তার evidence/result এখন দেখা যাচ্ছে।
Example:
Your clothes are wet. You have been walking in the rain.
তোমার কাপড় ভেজা—তুমি বৃষ্টির মধ্যে হাঁটছিলে/হেঁটে এসেছ।
1️⃣7️⃣ Stative Verb-এর ক্ষেত্রে সতর্কতা ⚠️
know, believe, understand, want, need, own, belong ইত্যাদি stative verb সাধারণত Continuous-এ ব্যবহার করা হয় না।
❌ I have been knowing him for five years.
✅ I have known him for five years.
❌ I have been understanding English for two years.
✅ I have understood English for two years.
তবে দ্বিতীয় sentence-টি context অনুযায়ী অস্বাভাবিক হতে পারে; স্বাভাবিকভাবে বলা হবে:
I have understood English better over the last two years.
1️⃣8️⃣ Present Tense-এর চারটি Form একসাথে
এখন চারটি Present Tense compare করো:
① Present Simple
